    private void btnconsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnconsultarActionPerformed
    

    String email = JOptionPane.showInputDialog(
            this,
            "Digite o e-mail do usuário:"
    );

    if (email == null || email.isEmpty()) {
        return;
    }

    String sql =
            "SELECT id_usuario, nome, email "
            + "FROM usuario "
            + "WHERE email = ?";

    try {

        Connection conexaoBanco = conexao.conectar();

        PreparedStatement comando =
                conexaoBanco.prepareStatement(sql);

        comando.setString(1, email);

        java.sql.ResultSet resultado =
                comando.executeQuery();

        if (resultado.next()) {

            int id = resultado.getInt("id_usuario");
            String nome = resultado.getString("nome");
            String emailBanco = resultado.getString("email");

            JOptionPane.showMessageDialog(
                    this,
                    "ID: " + id
                    + "\nNome: " + nome
                    + "\nEmail: " + emailBanco
            );

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "Usuário não encontrado!"
            );
        }

        resultado.close();
        comando.close();
        conexaoBanco.close();

    } catch (SQLException erro) {

        JOptionPane.showMessageDialog(
                this,
                "Erro ao consultar: " + erro.getMessage()
        );
    }
    
    }//GEN-LAST:event_btnconsultarActionPerformed

