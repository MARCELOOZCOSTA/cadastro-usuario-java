    private void btncadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncadastrarActionPerformed
        String nome = txtnome.getText();
        String email = txtemail.getText();
       String senha = new String(txtSenha.getPassword());

if (nome.isEmpty() || email.isEmpty() || senha.isEmpty()) {

    JOptionPane.showMessageDialog(
            this,
            "Preencha todos os campos!"
    );

    return;
}

String senhaHash = BCrypt.hashpw(
        senha,
        BCrypt.gensalt(12)
);

String sql = "INSERT INTO usuario (nome, email, senha) VALUES (?, ?, ?)";

try {

    Connection conexaoBanco = conexao.conectar();

    PreparedStatement comando =
            conexaoBanco.prepareStatement(sql);

    comando.setString(1, nome);
    comando.setString(2, email);
    comando.setString(3, senhaHash);

    comando.executeUpdate();

    JOptionPane.showMessageDialog(
            this,
            "Usuário cadastrado com sucesso!"
    );

    txtnome.setText("");
    txtemail.setText("");
    txtSenha.setText("");

    comando.close();
    conexaoBanco.close();

} catch (SQLException erro) {

    JOptionPane.showMessageDialog(
            this,
            "Erro ao cadastrar: " + erro.getMessage()
    );
}
    }//GEN-LAST:event_btncadastrarActionPerformed

    private void btnalterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnalterarActionPerformed
        
    String id = txtidusuario.getText();
    String nome = txtnome.getText();
    String email = txtemail.getText();
    String senha = new String(txtSenha.getPassword());

    if (id.isEmpty() || nome.isEmpty() || email.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione um usuário e preencha os campos!"
        );

        return;
    }

    try {

        Connection conexaoBanco = conexao.conectar();

        if (senha.isEmpty()) {

            String sql = "UPDATE usuario "
                    + "SET nome = ?, email = ? "
                    + "WHERE id_usuario = ?";

            PreparedStatement comando =
                    conexaoBanco.prepareStatement(sql);

            comando.setString(1, nome);
            comando.setString(2, email);
            comando.setInt(3, Integer.parseInt(id));

            comando.executeUpdate();

            comando.close();

        } else {

            String senhaHash = BCrypt.hashpw(
                    senha,
                    BCrypt.gensalt(12)
            );

            String sql = "UPDATE usuario "
                    + "SET nome = ?, email = ?, senha = ? "
                    + "WHERE id_usuario = ?";

            PreparedStatement comando =
                    conexaoBanco.prepareStatement(sql);

            comando.setString(1, nome);
            comando.setString(2, email);
            comando.setString(3, senhaHash);
            comando.setInt(4, Integer.parseInt(id));

            comando.executeUpdate();

            comando.close();
        }

        conexaoBanco.close();

        JOptionPane.showMessageDialog(
                this,
                "Usuário alterado com sucesso!"
        );

        

        txtidusuario.setText("");
        txtnome.setText("");
        txtemail.setText("");
        txtSenha.setText("");

    } catch (SQLException erro) {

        JOptionPane.showMessageDialog(
                this,
                "Erro ao alterar: " + erro.getMessage()
        );
    }

    }//GEN-LAST:event_btnalterarActionPerformed

    private void btnexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnexcluirActionPerformed
       

    String id = txtidusuario.getText();

    if (id.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Selecione um usuário!"
        );

        return;
    }

    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este usuário?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
    );

    if (resposta == JOptionPane.YES_OPTION) {

        String sql = "DELETE FROM usuario WHERE id_usuario = ?";

        try {

            Connection conexaoBanco = conexao.conectar();

            PreparedStatement comando =
                    conexaoBanco.prepareStatement(sql);

            comando.setInt(
                    1,
                    Integer.parseInt(id)
            );

            comando.executeUpdate();

            comando.close();
            conexaoBanco.close();

            JOptionPane.showMessageDialog(
                    this,
                    "Usuário excluído com sucesso!"
            );

           

            txtidusuario.setText("");
            txtnome.setText("");
            txtemail.setText("");
            txtSenha.setText("");

        } catch (SQLException erro) {

            JOptionPane.showMessageDialog(
                    this,
                    "Erro ao excluir: " + erro.getMessage()
            );
        }
    }

    }//GEN-LAST:event_btnexcluirActionPerformed

